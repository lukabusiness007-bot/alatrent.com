import pg from 'pg';
import { attachDatabasePool } from '@vercel/functions';
import { AsyncLocalStorage } from 'node:async_hooks';
import { DatabaseSync } from 'node:sqlite';
import { readFileSync } from 'node:fs';
import path from 'node:path';

export const SQLITE_SCHEMA = `
CREATE TABLE IF NOT EXISTS entities (kind TEXT NOT NULL,id TEXT NOT NULL,value TEXT NOT NULL,PRIMARY KEY(kind,id));
CREATE TABLE IF NOT EXISTS sessions (token TEXT PRIMARY KEY,expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS auth (id INTEGER PRIMARY KEY CHECK(id=1),salt TEXT NOT NULL,hash TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS limits (key TEXT PRIMARY KEY,count INTEGER NOT NULL,expires INTEGER NOT NULL);`;

/** @type {AsyncLocalStorage<{database: DatabaseSync, client: import('pg').PoolClient, write: boolean}>} */
const scope = new AsyncLocalStorage();
/** @type {import('pg').Pool | undefined} */
let pool;
/** @type {Promise<void> | undefined} */
let initialized;
const tables = {
  entities: { keys: ['kind', 'id'], columns: ['kind', 'id', 'value'] },
  sessions: { keys: ['token'], columns: ['token', 'expires'] },
  auth: { keys: ['id'], columns: ['id', 'salt', 'hash'] },
  limits: { keys: ['key'], columns: ['key', 'count', 'expires'] },
};
const lock = 'SELECT pg_advisory_xact_lock(1836016740, hashtext($1))';
export function databaseSchema() {
  const name = process.env.POSTGRES_SCHEMA || 'alat_rent';
  if (!/^alat_rent(?:_[a-z0-9_]+)?$/.test(name)) throw new Error('Invalid application schema.');
  return name;
}
export const postgresConfigured = () => !!(process.env.POSTGRES_URL || process.env.DATABASE_URL || process.env.POSTGRES_PRISMA_URL);

export function postgresPool() {
  if (pool) return pool;
  const raw = process.env.POSTGRES_URL || process.env.DATABASE_URL || process.env.POSTGRES_PRISMA_URL;
  if (!raw) throw new Error('Postgres connection is not configured.');
  const url = new URL(raw.replace('postgres\\:', 'postgres:'));
  for (const name of ['sslmode', 'sslrootcert', 'sslcert', 'sslkey', 'pgbouncer', 'supa']) url.searchParams.delete(name);
  const local = ['localhost', '127.0.0.1', '::1', '[::1]'].includes(url.hostname);
  const supabase = /\.(supabase\.com|supabase\.co)$/.test(url.hostname);
  pool = new pg.Pool({
    connectionString: url.href,
    ssl: local ? false : { rejectUnauthorized: true, ...(supabase ? { ca: readFileSync(path.join(process.cwd(), 'config/certs/supabase-ca.crt'), 'utf8') } : {}) },
    max: 3, connectionTimeoutMillis: 15000, idleTimeoutMillis: 10000,
    allowExitOnIdle: true,
  });
  if (process.env.VERCEL === '1') attachDatabasePool(pool);
  pool.on('error', () => { /* The next request reconnects; never log connection secrets. */ });
  return pool;
}

/** @param {DatabaseSync} fallback @returns {DatabaseSync} */
export function requestDatabase(fallback) {
  if (!postgresConfigured()) return fallback;
  const context = scope.getStore();
  if (!context) throw new Error('Persistent database access requires withDatabase().');
  return context.database;
}

/** @param {import('pg').PoolClient} client */
async function schema(client) {
  await client.query(`
    CREATE SCHEMA IF NOT EXISTS ${databaseSchema()};
    REVOKE ALL ON SCHEMA ${databaseSchema()} FROM PUBLIC;
    CREATE TABLE IF NOT EXISTS ${databaseSchema()}.entities (
      position BIGINT GENERATED BY DEFAULT AS IDENTITY,
      kind TEXT NOT NULL, id TEXT NOT NULL, value JSONB NOT NULL, PRIMARY KEY(kind,id));
    CREATE TABLE IF NOT EXISTS ${databaseSchema()}.sessions (token TEXT PRIMARY KEY, expires BIGINT NOT NULL);
    CREATE TABLE IF NOT EXISTS ${databaseSchema()}.auth (id INTEGER PRIMARY KEY CHECK(id=1),salt TEXT NOT NULL,hash TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS ${databaseSchema()}.limits (key TEXT PRIMARY KEY,count INTEGER NOT NULL,expires BIGINT NOT NULL);
    CREATE TABLE IF NOT EXISTS ${databaseSchema()}.media (name TEXT PRIMARY KEY,mime TEXT NOT NULL,data BYTEA NOT NULL);
    ALTER TABLE ${databaseSchema()}.entities ENABLE ROW LEVEL SECURITY;
    ALTER TABLE ${databaseSchema()}.sessions ENABLE ROW LEVEL SECURITY;
    ALTER TABLE ${databaseSchema()}.auth ENABLE ROW LEVEL SECURITY;
    ALTER TABLE ${databaseSchema()}.limits ENABLE ROW LEVEL SECURITY;
    ALTER TABLE ${databaseSchema()}.media ENABLE ROW LEVEL SECURITY;
  `);
}

/** @param {import('pg').PoolClient} client */
async function load(client) {
  const database = new DatabaseSync(':memory:');
  database.exec(SQLITE_SCHEMA);
  try {
    // Read rows directly instead of building one large JSONB aggregate inside
    // PostgreSQL. The caller's transaction keeps all four reads consistent.
    for (const [table, config] of Object.entries(tables)) {
      const { rows } = await client.query(`SELECT ${config.columns.join(',')} FROM ${databaseSchema()}.${table}${table === 'entities' ? ' ORDER BY position' : ''}`);
      const insert = database.prepare(`INSERT INTO ${table} (${config.columns.join(',')}) VALUES (${config.columns.map(() => '?').join(',')})`);
      for (const row of rows) insert.run(...config.columns.map(column =>
        column === 'value' ? JSON.stringify(row[column]) : column === 'expires' ? Number(row[column]) : row[column]));
    }
    return database;
  } catch (error) {
    database.close();
    throw error;
  }
}

/** @param {DatabaseSync} database */
function snapshot(database) {
  return Object.fromEntries(Object.entries(tables).map(([table, config]) => [table,
    new Map(database.prepare(`SELECT ${config.columns.join(',')} FROM ${table}`).all().map(row =>
      [JSON.stringify(config.keys.map(key => row[key])), row])),
  ]));
}

/** @param {import('pg').PoolClient} client @param {DatabaseSync} database @param {ReturnType<typeof snapshot>} before */
async function persist(client, database, before) {
  const after = snapshot(database);
  for (const [table, config] of Object.entries(tables)) {
    const deleted = [...before[table]].filter(([key]) => !after[table].has(key)).map(([, row]) => row);
    for (let offset = 0; offset < deleted.length; offset += 100) {
      const args = [];
      const predicates = deleted.slice(offset, offset + 100).map(row => '(' + config.keys.map(key => {
        args.push(row[key]); return key + '=$' + args.length;
      }).join(' AND ') + ')').join(' OR ');
      await client.query(`DELETE FROM ${databaseSchema()}.${table} WHERE ${predicates}`, args);
    }
    const changed = [...after[table]].filter(([key, row]) => JSON.stringify(before[table].get(key)) !== JSON.stringify(row)).map(([, row]) => row);
    // Keep bulk imports bounded for hosted poolers; all batches share the
    // request transaction. No credentials or user values appear in SQL.
    for (let offset = 0; offset < changed.length; offset += 100) {
      const args = [];
      const values = changed.slice(offset, offset + 100).map(row => '(' + config.columns.map(column => {
        args.push(row[column]); return '$' + args.length + (column === 'value' ? '::jsonb' : '');
      }).join(',') + ')').join(',');
      const updates = config.columns.filter(column => !config.keys.includes(column)).map(column => column + '=EXCLUDED.' + column).join(',');
      await client.query(`INSERT INTO ${databaseSchema()}.${table} (${config.columns.join(',')}) VALUES ${values} ON CONFLICT (${config.keys.join(',')}) DO UPDATE SET ${updates}`, args);
    }
  }
}

/** @param {import('pg').PoolClient} client @param {{meta: string[], requireAuth?: boolean}} completion */
async function initializationComplete(client, completion) {
  try {
    const { rows } = await client.query(`SELECT
      (SELECT count(*) FROM ${databaseSchema()}.entities WHERE kind='meta' AND id=ANY($1::text[]) AND value='true'::jsonb) AS completed,
      (NOT $2::boolean OR EXISTS(SELECT 1 FROM ${databaseSchema()}.auth WHERE id=1)) AS auth_ready`,
    [completion.meta, !!completion.requireAuth]);
    return Number(rows[0].completed) === completion.meta.length && rows[0].auth_ready;
  } catch (error) {
    // A fresh schema still follows the locked bootstrap path below.
    if (error.code === '42P01' || error.code === '3F000') return false;
    throw error;
  }
}

/** @param {() => void} initialize @param {{meta: string[], requireAuth?: boolean} | undefined} completion */
async function ensureInitialized(initialize, completion) {
  if (initialized) return initialized;
  initialized = (async () => {
    const client = await postgresPool().connect();
    let database, started = false;
    try {
      // Completed migrations need no write lock, DDL, or second catalog load
      // on every serverless cold start. Normal requests still load fresh data.
      if (completion?.meta.length && await initializationComplete(client, completion)) return;
      await client.query('BEGIN');
      started = true;
      await client.query(lock, [databaseSchema()]);
      await schema(client);
      database = await load(client);
      const before = snapshot(database);
      scope.run({ database, client, write: true }, initialize);
      await persist(client, database, before);
      await client.query('COMMIT');
    } catch (error) { if (started) await client.query('ROLLBACK'); throw error; }
    finally { database?.close(); client.release(); }
  })().catch(error => { initialized = undefined; throw error; });
  return initialized;
}

/**
 * A request uses a fresh PostgreSQL snapshot. Existing synchronous domain rules
 * run in isolated in-memory SQLite; only PostgreSQL is authoritative. Mutations
 * lock across instances and commit the complete diff before returning success.
 * @template T
 * @param {() => void} initialize
 * @param {() => T | Promise<T>} fn
 * @param {boolean} [write]
 * @param {{meta: string[], requireAuth?: boolean}} [completion]
 * @returns {Promise<T>}
 */
export async function withPersistentDatabase(initialize, fn, write = false, completion) {
  if (!postgresConfigured()) return fn();
  const nested = scope.getStore();
  if (nested) {
    if (write && !nested.write) throw new Error('Cannot write inside a read-only database request.');
    return fn();
  }
  await ensureInitialized(initialize, completion);
  const client = await postgresPool().connect();
  let database;
  try {
    await client.query(write ? 'BEGIN' : 'BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY');
    if (write) await client.query(lock, [databaseSchema()]);
    database = await load(client);
    const before = write ? snapshot(database) : undefined;
    if (!write) database.exec('PRAGMA query_only=ON');
    const result = await scope.run({ database, client, write }, fn);
    if (before) await persist(client, database, before);
    await client.query('COMMIT');
    return result;
  } catch (error) { await client.query('ROLLBACK'); throw error; }
  finally { database?.close(); client.release(); }
}

/** @param {string} name @param {string} mime @param {Buffer} bytes */
export async function savePersistentMedia(name, mime, bytes) {
  const context = scope.getStore();
  if (!context?.write) throw new Error('Upload requires an authenticated write request.');
  await context.client.query(`INSERT INTO ${databaseSchema()}.media(name,mime,data) VALUES($1,$2,$3)`, [name,mime,bytes]);
}
/** @param {string} name */
export async function readPersistentMedia(name) {
  const context = scope.getStore();
  if (!context) throw new Error('Media access requires a database request.');
  const { rows } = await context.client.query(`SELECT mime,data FROM ${databaseSchema()}.media WHERE name=$1`, [name]);
  return rows[0];
}

/** @param {string} file */
export async function importLocalDatabase(file) {
  const source = new DatabaseSync(file, { readOnly: true });
  const client = await postgresPool().connect();
  try {
    await client.query('BEGIN'); await client.query(lock, [databaseSchema()]); await schema(client);
    for (const [table, config] of Object.entries(tables)) {
      if (!source.prepare("SELECT name FROM sqlite_master WHERE type='table' AND name=?").get(table)) continue;
      // Sessions and rate limits are ephemeral; only inventory and admin credentials migrate.
      if (!['entities', 'auth'].includes(table)) continue;
      const rows = source.prepare(`SELECT ${config.columns.join(',')} FROM ${table}`).all();
      const args = [];
      const values = rows.map(row => '(' + config.columns.map(column => {
        args.push(row[column]); return '$' + args.length + (column === 'value' ? '::jsonb' : '');
      }).join(',') + ')').join(',');
      if (rows.length) await client.query(`INSERT INTO ${databaseSchema()}.${table} (${config.columns.join(',')}) VALUES ${values} ON CONFLICT (${config.keys.join(',')}) DO NOTHING`, args);
    }
    await client.query('COMMIT');
  } catch (error) { await client.query('ROLLBACK'); throw error; }
  finally { source.close(); client.release(); }
}
