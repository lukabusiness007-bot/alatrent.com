import type { Locale, Localized } from '../types';
export type Tier = { from: number; percent: number };
export type PriceRule = {
  tiers: Tier[];
  floorPercent: number;
  weekendPercent: number;
  quietPercent: number;
  quietDays: number[];
};
export type Team = { id: string; name: string; customerIds: string[]; discount: number };
export type ToolOptions = {
  costPerDay?: number | null;
  preparationCost?: number | null;
  rule?: PriceRule;
  instructions: string;
  manualUrl: string;
  videoUrl: string;
  model: string;
  relatedIds: string[];
  alternativeIds: string[];
};
export type Bundle = {
  id: string;
  name: string;
  description: string;
  toolIds: string[];
  discount: number;
  published: boolean;
};
export type ReferralProgram = {
  enabled: boolean;
  percent: number;
  maxDiscount: number;
  minimum: number;
  reward: number;
  monthlyLimit: number;
  minContributionPercent: number;
  pilotEndsAt: string;
  memberIds: string[];
};
export type Referral = {
  referrerId: string;
  code: string;
  policy: ReferralProgram;
  discount: number;
  status: 'pending' | 'granted' | 'limit' | 'reversed' | 'rejected';
  verified?: boolean;
};
export type ReferralReward = {
  orderId: string;
  referrerId: string;
  customerId: string;
  amount: number;
  createdAt: string;
  reversedAt?: string;
  reason?: string;
};
export type ReferralSummary = {
  policy: ReferralProgram;
  active: boolean;
  pending: number;
  successful: number;
  remaining: number;
  earned: number;
  reversed: number;
};
export type CommerceConfig = {
  rule: PriceRule;
  categories: Record<string, PriceRule>;
  clubThreshold: number;
  clubPercent: number;
  referralCredit: number; // Legacy setting; new orders use referralProgram.
  referralProgram: ReferralProgram;
  creditLimitPercent: number;
  returnTime: string;
  reviewUrl: string;
  templates: Record<string, string>;
  templateLanguage: string;
  enabled: boolean;
};
export type CartItem = { toolId: string; quantity: number; start: string; end: string };
export type Line = CartItem & {
  name: Localized;
  slug: string;
  days: number;
  base: number | null;
  total: number | null;
  saving: number;
  reason: string;
  price: number | null;
  rule: PriceRule;
  clubPercent: number;
  bundlePercent: number;
  instructions: ToolOptions;
};
export type Quote = {
  referral?: Referral;
  items: Line[];
  rentalTotal: number | null;
  baseTotal: number | null;
  saving: number;
  deliveryTotal: number;
  credit: number;
  total: number | null;
};
export type Customer = {
  id: string;
  phone: string;
  name: string;
  address: string;
  company: string;
  salt: string;
  hash: string;
  recoveryHash: string;
  credit: number;
  referralCode: string;
  referredBy?: string;
  referredAt?: string;
  referralPaused?: boolean;
  rewarded?: boolean;
  partnerPercent: number;
  marketing: boolean;
  createdAt: string;
};
export type PublicCustomer = Omit<Customer, 'salt' | 'hash' | 'recoveryHash'> & {
  completed: number;
  tier: string;
  discount: number;
};
export type Order = Quote & {
  id: string;
  customerId?: string;
  teamId?: string;
  accessHash: string;
  accessToken: string;
  idempotency: string;
  name: string;
  phone: string;
  email: string;
  address: string;
  note: string;
  company: string;
  delivery: 'pickup' | 'standard' | 'express';
  status: 'pending' | 'confirmed' | 'active' | 'completed' | 'cancelled';
  paid: boolean;
  locale: Locale;
  whatsapp: boolean;
  marketing: boolean;
  consentAt: string;
  createdAt: string;
  completedAt?: string;
  extension?: { end: string; status: 'pending' | 'approved' | 'rejected'; extra: number | null };
  returnTime: string;
  adjustment: number;
  creditReturned?: boolean;
  referralVersion?: number;
  creditContributionTarget?: number;
  referralCosts?: number;
};
export type Message = {
  id: string;
  orderId?: string;
  customerId?: string;
  phone: string;
  event: string;
  params: string[];
  status: 'queued' | 'sending' | 'sent' | 'delivered' | 'read' | 'failed' | 'unknown' | 'cancelled';
  attempts: number;
  nextAt: number;
  createdAt: string;
  providerId?: string;
  error?: string;
  template: string;
  language: string;
};
export type Project = {
  id: string;
  customerId: string;
  name: string;
  items: CartItem[];
  createdAt: string;
};
export type Watch = {
  id: string;
  customerId: string;
  item: CartItem;
  createdAt: string;
  notified: boolean;
};
